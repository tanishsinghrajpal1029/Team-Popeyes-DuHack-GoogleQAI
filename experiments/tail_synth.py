"""Depth-minimal exact Ry + CZ blocks for the end of a Baertschi-Eidenbenz arm (bonus track).

The B-E unitary on an arm of b qubits decides positions b, b-1, ..., 2 with nearest-neighbour
sweeps. The sweeps for the last m0 positions run on the same few qubits with no parallelism
left (a 41-moment tail for m0 = 4 at k >= 4). Those sweeps implement the small Dicke unitary
    U_{m0}: |0^{m0-r} 1^r>  ->  |D^{m0}_r>   for every r <= rmax = min(k, m0)
(ones at the END of the position list, as in main.dicke_unitary_ops), which is a small
isometry we can synthesize directly: Ry layers and brickwork CZ layers on a path of m0 qubits,
fewest layers first (the bonus scores moments, 2L+1 for L CZ layers; CZ count is irrelevant).

  OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 .venv/bin/python experiments/tail_synth.py \
      --cases 3,3 4,3 4,4 5,3 5,4 5,5 --seeds 0 1 2 3 --time-limit 600 --workers 24
  .venv/bin/python experiments/tail_synth.py --export      # write _TAIL into main.py

Results: experiments/results/tail/U<m0>_r<rmax>_<shape>_s<seed>.json
"""

import argparse
import itertools
import json
import math
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from scs_synth import BatchCircuit, basis, solve  # noqa: E402
from synth import brickwork, shape_coords, shape_edges  # noqa: E402

OUT = os.path.join(HERE, "results", "tail")
TOL = 1e-12


def dicke_vec(w: int, r: int) -> np.ndarray:
    d = np.zeros(2**w)
    for c in itertools.combinations(range(w), r):
        d[sum(1 << (w - 1 - q) for q in c)] = 1.0
    return d / np.linalg.norm(d)


def tail_io(m0: int, rmax: int) -> tuple[np.ndarray, np.ndarray]:
    """Columns: inputs |0^{m0-r} 1^r> and targets |D^{m0}_r>, r = 0..rmax (cirq big-endian)."""
    ins = [basis(m0, "0" * (m0 - r) + "1" * r) for r in range(rmax + 1)]
    outs = [dicke_vec(m0, r) for r in range(rmax + 1)]
    return np.array(ins).T, np.array(outs).T


def verify(entry: dict) -> float:
    """Max amplitude error of the stored block against its defining isometry (common sign allowed)."""
    ins, outs = tail_io(entry["m0"], entry["rmax"])
    got = BatchCircuit(entry["m0"], entry["cz_layers"]).apply(np.array(entry["params"]), ins)
    return float(min(np.abs(got - outs).max(), np.abs(got + outs).max()))


def search(m0, rmax, shape="path", seed=0, max_layers=30, restarts=8, time_limit=600.0, log=print):
    """Smallest brickwork layer count on `shape` whose angles reach the exact isometry."""
    rng = np.random.default_rng(seed)
    coords = shape_coords(shape, m0)
    edges = shape_edges(coords)
    ins, outs = tail_io(m0, rmax)
    t0 = time.time()
    for L in range(1, max_layers + 1):
        layers = brickwork(edges, L)
        f, x = solve(m0, layers, ins, outs, rng, restarts)
        log(f"  U_{m0} r<={rmax} {shape} s{seed} L={L} cz={sum(map(len, layers))} infid={f:.1e} ({time.time() - t0:.0f}s)")
        if f < TOL:
            return dict(
                m0=m0, rmax=rmax, shape=shape, coords=coords, cz_layers=layers,
                params=[float(v) for v in x], infidelity=float(f), layers=L,
                cz=sum(map(len, layers)), seed=seed, seconds=round(time.time() - t0, 1),
            )
        if time.time() - t0 > time_limit:
            log(f"  U_{m0} r<={rmax} {shape} s{seed}: time limit at L={L}")
            return None
    return None


def _job(args):
    m0, rmax, shape, seed, time_limit, restarts = args
    os.makedirs(OUT, exist_ok=True)
    stem = os.path.join(OUT, f"U{m0}_r{rmax}_{shape}_s{seed}")

    def log(s):
        with open(stem + ".log", "a") as fh:
            fh.write(f"{time.strftime('%H:%M:%S')} {s}\n")

    res = search(m0, rmax, shape, seed, time_limit=time_limit, restarts=restarts, log=log)
    if res is not None:
        with open(stem + ".json", "w") as fh:
            json.dump(res, fh)
        return f"U_{m0} r<={rmax} {shape} seed={seed}: {res['layers']} layers ({2 * res['layers'] + 1} moments), {res['cz']} CZ, {res['seconds']}s"
    return f"U_{m0} r<={rmax} {shape} seed={seed}: FAILED"


BEGIN = "# BEGIN TAIL TABLE (generated by experiments/tail_synth.py --export; do not edit)\n"
END = "# END TAIL TABLE\n"


def export_table(main_path=os.path.join(os.path.dirname(HERE), "main.py")):
    """Best (fewest layers, then fewest CZ) verified block per (m0, rmax) -> _TAIL in main.py.

    Only path-shaped blocks are exported: the arm is a path and the block acts on its first m0
    positions, so a block needs no layout of its own.
    """
    best = {}
    for name in sorted(os.listdir(OUT)) if os.path.isdir(OUT) else []:
        if not name.endswith(".json"):
            continue
        with open(os.path.join(OUT, name)) as fh:
            r = json.load(fh)
        if r["shape"] != "path":
            continue
        err = verify(r)
        if err > 1e-6:
            print(f"skip {name}: amplitude error {err:.1e}")
            continue
        key = (r["m0"], r["rmax"])
        if key not in best or (r["layers"], r["cz"]) < (best[key]["layers"], best[key]["cz"]):
            best[key] = r
    lines = [BEGIN, "_TAIL = {  # (m0, rmax): (cz_layers, ry_params); layers x moments in the comment\n"]
    for (m0, rmax), r in sorted(best.items()):
        layers = [[tuple(e) for e in l] for l in r["cz_layers"]]
        lines.append(f"    ({m0}, {rmax}): ({layers!r}, {[float(p) for p in r['params']]!r}),  # {r['layers']} layers, {2 * r['layers'] + 1} moments, seed {r['seed']}\n")
    lines += ["}\n", END]
    with open(main_path) as fh:
        src = fh.read()
    if BEGIN not in src or END not in src:
        sys.exit(f"markers {BEGIN.strip()!r} / {END.strip()!r} not found in {main_path}")
    head, rest = src.split(BEGIN)
    _, tail = rest.split(END)
    with open(main_path, "w") as fh:
        fh.write(head + "".join(lines) + tail)
    for (m0, rmax), r in sorted(best.items()):
        print(f"U_{m0} r<={rmax}: {r['layers']} layers = {2 * r['layers'] + 1} moments, {r['cz']} CZ (seed {r['seed']})")


def main_cli():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--export", action="store_true", help="write the best blocks into main.py and exit")
    ap.add_argument("--cases", nargs="+", default=["3,3", "4,3", "4,4"], help="m0,rmax pairs")
    ap.add_argument("--shapes", nargs="+", default=["path"])
    ap.add_argument("--seeds", type=int, nargs="+", default=[0])
    ap.add_argument("--time-limit", type=float, default=600.0, help="seconds per (case, shape, seed)")
    ap.add_argument("--restarts", type=int, default=8)
    ap.add_argument("--workers", type=int, default=os.cpu_count())
    args = ap.parse_args()
    if args.export:
        export_table()
        return
    jobs = [
        (int(c.split(",")[0]), int(c.split(",")[1]), s, seed, args.time_limit, args.restarts)
        for c in args.cases for s in args.shapes for seed in args.seeds
    ]
    with Pool(min(args.workers, len(jobs))) as pool:
        for summary in pool.imap_unordered(_job, jobs):
            print(summary, flush=True)


if __name__ == "__main__":
    main_cli()
